CATEGORY_TO_TEMPLATE = {
    # B2B
    "Навигация": _msg_navigation,
    "Финтех / Банки": _msg_banking,
    "Телеком": _msg_telecom,
    "EdTech / Образование": _msg_edtech,
    "Маркетплейс": _msg_marketplace,
    "Гос. технологии": _msg_govtech,
    "Доставка / Логистика": _msg_delivery,
    "Здравоохранение": _msg_healthcare,
    "Авиация / Транспорт": _msg_aviation,
    "CRM / ERP": _msg_crm,
    "Медиа": _msg_media,
    "Колл-центры": _msg_callcenter,
    # Dataset
    "Телевидение": _msg_dataset_tv,
    "Радио": _msg_dataset_radio,
    "Издательства": _msg_dataset_publishing,
    "Университеты": _msg_dataset_university,
    "Библиотеки": _msg_dataset_library,
    "Кино / Студии": _msg_dataset_film,
    "Газеты / СМИ": _msg_dataset_news,
    "Музыка": _msg_dataset_music,
    "Языковые институты": _msg_dataset_language_institute,
}


def generate_message(
    company_name: str,
    category: str,
    contact_name: str | None = None,
    use_case: str = "",
) -> str:
    fn = CATEGORY_TO_TEMPLATE.get(category)
    if fn:
        return fn(company_name, contact_name, use_case)
    # fallback generic
    greeting = _greeting(contact_name)
    return f"""{greeting}

Меня зовут {SENDER_NAME} из {SENDER_COMPANY} — казахстанские голосовые ИИ-технологии (TTS, STT, Voice Cloning) на казахском, русском и английском языках.

Хотели бы обсудить возможное сотрудничество с {company_name}. {use_case}

Буду рада показать демо. Когда удобно созвониться на 20–30 минут?{SIGNATURE}"""
